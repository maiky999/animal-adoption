package com.wsb.animaladoption.enums;

/**
 * Age group of the animal. Groups instead of an exact age, because the age of a found or shelter animal
 * is usually only estimated - and groups are what adopters actually filter by.
 */
public enum AnimalAgeEnum {
    /** Up to about 1 year (puppy, kitten). */
    YOUNG,
    /** About 1-7 years. */
    ADULT,
    /** Over about 7 years. */
    SENIOR
}
